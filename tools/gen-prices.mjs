// Regenerate build/prices.js from the pi-ai catalog under _ref (a local copy of
// the shipped package). Prices are the catalog's list price in USD per million
// tokens; a subscription route (OpenCode Go, Grok) is not billed this way, so
// the page labels the number as an estimate.
//
// usage: node tools/gen-prices.mjs [outFile]
import fs from 'node:fs'
import path from 'node:path'

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const dataDir = path.resolve(here, '..', '..', '..', '_ref', 'pi-ai', 'dist', 'providers', 'data')
const out = process.argv[2] ?? path.resolve(here, '..', 'build', 'prices.js')

const providers = ['opencode-go', 'xai', 'deepseek']
const prices = {}

const round = (value) => Math.round(value * 1e6) / 1e6

for (const provider of providers) {
  const file = path.join(dataDir, `${provider}.json`)
  if (!fs.existsSync(file)) {
    console.log(`skip ${provider}: no catalog file`)
    continue
  }
  const catalog = JSON.parse(fs.readFileSync(file, 'utf8'))
  for (const models of Object.values(catalog)) {
    if (models === null || typeof models !== 'object') continue
    for (const entry of Object.values(models)) {
      const id = entry?.id
      const cost = entry?.cost
      if (typeof id !== 'string' || cost === null || typeof cost !== 'object') continue
      const input = Number(cost.input)
      const output = Number(cost.output)
      if (!Number.isFinite(input) || !Number.isFinite(output)) continue
      const line = { input: round(input), output: round(output) }
      if (Number.isFinite(Number(cost.cacheRead))) line.cacheRead = round(Number(cost.cacheRead))
      if (Number.isFinite(Number(cost.cacheWrite))) line.cacheWrite = round(Number(cost.cacheWrite))
      prices[`${provider}/${id}`] = line
    }
  }
  console.log(`${provider}: ${Object.keys(prices).filter((key) => key.startsWith(`${provider}/`)).length} models`)
}

const body = `/**
 * List prices, USD per million tokens, as the pi-ai catalog carries them.
 *
 * Generated by tools/gen-prices.mjs — do not edit by hand. A subscription
 * route (OpenCode Go, Grok) is not billed per token; the page says "estimate"
 * for exactly that reason.
 */
export const PRICES = Object.freeze(${JSON.stringify(prices, null, 2)})
`
fs.writeFileSync(out, body)
console.log(`wrote ${out} (${Object.keys(prices).length} entries)`)
